from I2C import I2C

class SSD1306:
    def __init__(self, i2c):
        self._i2c = i2c

        self.writeCmd(0xAE);     #display off
    
        self.writeCmd(0x20);     #Page Addressing Mode:2
        self.writeCmd(0x02);
        
        self.writeCmd(0xB0);     #Page Start Address: 0
        
        self.writeCmd(0x00);     #Column Start Address: 0
        self.writeCmd(0x10);
        
        self.writeCmd(0xC8);     #Scan from COM63 to COM0
        
        self.writeCmd(0xDA);     #Alternative COM pin configuration
        self.writeCmd(0x12);
        
        self.writeCmd(0xA8);     #Line Number: 64
        self.writeCmd(0x3F);
        
        self.writeCmd(0x40);     #set start line address
        
        self.writeCmd(0xD3);     #set display offset
        self.writeCmd(0x00);
        
        self.writeCmd(0xA1);     #column address 127 is mapped to SEG0
        
        self.writeCmd(0xD5);     #OSC freq and display freq div
        self.writeCmd(0xF0);
        
        self.writeCmd(0xD9);     #Pre-charge Period
        self.writeCmd(0x22);
        
        self.writeCmd(0xDB);     #VCOMH deselect level，0.77 x VC
        self.writeCmd(0x20);
        
        self.writeCmd(0x8D);     #Enable charge pump during display on
        self.writeCmd(0x14);
        
        self.writeCmd(0xAF);     #display on

    def writeCmd(self, cmd):
        self._i2c.xfer(0x78>>1, [I2C.Message(b'\x00' + chr(cmd))])

    def writeData(self, data):
        self._i2c.xfer(0x78>>1, [I2C.Message(b'\x40' + chr(data))])

    ''' Dispaly RAM Structure, PpCx-b0...PpCx-b7 make a data byte
    P0C0-b0   P0C1-b0   P0C2-b0   ...   P0C126-b0   P0C127-b0
    P0C0-b1   P0C1-b1   P0C2-b1   ...   P0C126-b1   P0C127-b1
       .         .                ...       .           .
       .         .                ...       .           .
    P0C0-b6   P0C1-b6   P0C2-b6   ...   P0C126-b6   P0C127-b6
    P0C0-b7   P0C1-b7   P0C2-b7   ...   P0C126-b7   P0C127-b7
       .         .                ...       .           .
       .         .                ...       .           .
       .         .                ...       .           .
    P7C0-b0   P7C1-b0   P7C2-b0   ...   P7C126-b0   P7C127-b0
    P7C0-b1   P7C1-b1   P7C2-b1   ...   P7C126-b1   P7C127-b1
       .         .                ...       .           .
       .         .                ...       .           .
    P7C0-b6   P7C1-b6   P7C2-b6   ...   P7C126-b6   P7C127-b6
    P7C0-b7   P7C1-b7   P7C2-b7   ...   P7C126-b7   P7C127-b7 '''
    DispRAM = [[0] * 128 for i in range(8)]

    def DispRAMSet(self, x, y, val):
        if val == 0: self.DispRAM[y/8][x] &= ~(1 << (y%8))
        else:        self.DispRAM[y/8][x] |=  (1 << (y%8))

    def update(self, page0, column0, page1, column1):
        for page in range(page0, page1+1):
            self.writeCmd(0xB0 | page)
            self.writeCmd(0x00 | ((column0   )&0x0F))
            self.writeCmd(0x10 | ((column0>>4)&0x0F))

            for column in range(column0, column1+1):
                self.writeData(self.DispRAM[page][column])

    def drawLine(self, x0, y0, x1, y1, val):
        if x0 == x1:
            for y in range(y0, y1+1): self.DispRAMSet(x0, y, val)
        elif y0 == y1:
            for x in range(x0, x1+1): self.DispRAMSet(x, y0, val)
        else:
            for x in range(x0, x1+1): self.DispRAMSet(x, y0+(y1-y0)*(x-x0)/(x1-x0), val)
        self.update(y0//8, x0, y1//8, x1)

    def drawRect(self, x0, y0, x1, y1, val):
        self.drawLine(x0, y0, x1, y0, val)
        self.drawLine(x1, y0, x1, y1, val)
        self.drawLine(x0, y1, x1, y1, val)
        self.drawLine(x0, y0, x0, y1, val)

    def fillRect(self, x0, y0, x1, y1, val):
        for y in range(y0, y1+1):
            self.drawLine(x0, y, x1, y, val)

